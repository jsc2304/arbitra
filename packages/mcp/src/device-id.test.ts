/**
 * device-id stability tests (spec §I.1).
 *
 * `deriveDeviceId` mixes `os.hostname()` with the first non-loopback MAC (or
 * a persistent random id at `~/.config/arbitra/machine-id.txt` when no MAC
 * is available). We can't override the network interfaces from userland
 * without DI, so these tests cover:
 *
 *   1. Same hostname + same machine state → same id across calls (the most
 *      important contract).
 *   2. The persistent machine-id file is created on first read (when no MAC
 *      path was taken) and re-used on subsequent reads.
 *
 * Direct hostname/MAC-permutation testing would need `hostname()` /
 * `networkInterfaces()` to be injectable. That's a refactor worth doing if
 * the surface area grows; for now we exercise observable behaviour.
 */

import test from "node:test";
import assert from "node:assert/strict";
import {
  mkdtempSync,
  existsSync,
  readFileSync,
  writeFileSync,
  mkdirSync,
  rmSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

import { deriveDeviceId } from "./credentials.js";

const ORIGINAL_HOME = process.env.HOME;

function withTempHome(): string {
  const home = mkdtempSync(join(tmpdir(), "arbitra-did-test-"));
  process.env.HOME = home;
  return home;
}

function restoreHome(): void {
  if (ORIGINAL_HOME === undefined) delete process.env.HOME;
  else process.env.HOME = ORIGINAL_HOME;
}

test("deriveDeviceId is stable across two consecutive calls", () => {
  withTempHome();
  try {
    const a = deriveDeviceId();
    const b = deriveDeviceId();
    assert.equal(a, b);
    assert.equal(a.length, 16);
    assert.match(a, /^[0-9a-f]{16}$/);
  } finally {
    restoreHome();
  }
});

test("deriveDeviceId reuses persistent machine-id file when one exists", () => {
  // Pre-seed the persistent file. On hosts with a usable MAC the device id
  // will derive from the MAC and ignore this file, in which case both reads
  // still match each other (per the previous test) — the contract under
  // test here is "if the file ends up being read, the same content yields
  // the same id". We verify the file is not regenerated by either call.
  const home = withTempHome();
  try {
    const path = join(home, ".config", "arbitra", "machine-id.txt");
    mkdirSync(join(home, ".config", "arbitra"), { recursive: true, mode: 0o700 });
    const seeded = "deadbeefcafebabe1234567890abcdef";
    writeFileSync(path, seeded, { mode: 0o600 });

    const a = deriveDeviceId();
    const b = deriveDeviceId();
    assert.equal(a, b);

    // The seeded file must still be there (not regenerated).
    assert.ok(existsSync(path));
    assert.equal(readFileSync(path, "utf-8"), seeded);
  } finally {
    restoreHome();
  }
});

test("deriveDeviceId creates the persistent file when missing and reuses it", () => {
  const home = withTempHome();
  try {
    const path = join(home, ".config", "arbitra", "machine-id.txt");
    // Ensure the file does NOT exist at start.
    rmSync(path, { force: true });

    const a = deriveDeviceId();
    const b = deriveDeviceId();
    assert.equal(a, b);

    // On hosts where the MAC path resolves first, the persistent file may
    // not be created. On MAC-less hosts (containers, some CI), it IS
    // created. Either way the id is stable — that's the contract.
    if (existsSync(path)) {
      const content = readFileSync(path, "utf-8");
      assert.match(content.trim(), /^[0-9a-f]{32}$/);
    }
  } finally {
    restoreHome();
  }
});
